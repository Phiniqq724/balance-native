# Balance icon: the cell "B", drawn as a heat map. Writes the adaptive-icon vectors and a PNG proof.
import sys, os
from PIL import Image, ImageDraw
RES = sys.argv[1]; OUT = sys.argv[2]
B = ["1110", "1001", "1110", "1001", "1110"]
EMPTY = "#2B2420"
# Heat climbs from the bottom-left of the spine to the bowls' tips, like a month warming up on the grid.
RAMP = ["#B44A24", "#C9532A", "#DD5F31", "#EE6A3B", "#FF7444"]
def heat(r, c):
    t = ((4 - r) + c) / 7  # 0 at bottom-left, 1 at top-right
    return RAMP[min(4, round(t * 4))]
CELL, GAP = 8.6, 2.2
W = 4 * CELL + 3 * GAP; H = 5 * CELL + 4 * GAP
X0 = 54 - W / 2; Y0 = 54 - H / 2
RAD = CELL * 0.28

def rr(x, y, w, h, r):
    return (f"M{x+r:.2f},{y:.2f}h{w-2*r:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},{r:.2f}v{h-2*r:.2f}"
            f"a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},{r:.2f}h-{w-2*r:.2f}a{r:.2f},{r:.2f} 0 0 1 -{r:.2f},-{r:.2f}"
            f"v-{h-2*r:.2f}a{r:.2f},{r:.2f} 0 0 1 {r:.2f},-{r:.2f}z")

def cells():
    for r in range(5):
        for c in range(4):
            yield r, c, X0 + c * (CELL + GAP), Y0 + r * (CELL + GAP), B[r][c] == "1"

HEAD = '<?xml version="1.0" encoding="utf-8"?>\n'
VEC = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n'
       '    android:viewportWidth="108"\n    android:viewportHeight="108">\n')

fg = [HEAD, "<!-- The cell B as a heat map: empty cells in the grid's blank ink, the letter warming toward today. Generated by scripts/icon.py. -->\n", VEC]
groups = {}
for r, c, x, y, on in cells():
    groups.setdefault(heat(r, c) if on else EMPTY, []).append(rr(x, y, CELL, CELL, RAD))
for color, paths in groups.items():
    fg.append(f'    <path android:fillColor="{color}" android:pathData="{"".join(paths)}" />\n')
fg.append("</vector>\n")
open(f"{RES}/drawable/ic_launcher_foreground.xml", "w").write("".join(fg))

mono = [HEAD, "<!-- Themed icon: only the letter's cells. -->\n", VEC,
        '    <path android:fillColor="#FFFFFFFF" android:pathData="' + "".join(rr(x, y, CELL, CELL, RAD) for r, c, x, y, on in cells() if on) + '" />\n</vector>\n']
open(f"{RES}/drawable/ic_launcher_monochrome.xml", "w").write("".join(mono))

bg = [HEAD, "<!-- Warm charcoal with a faint ember glow behind the letter. -->\n",
      VEC.replace("<vector ", '<vector xmlns:aapt="http://schemas.android.com/aapt"\n    ', 1),
      '    <path android:pathData="M0,0h108v108h-108z">\n        <aapt:attr name="android:fillColor">\n'
      '            <gradient android:type="radial" android:centerX="54" android:centerY="50" android:gradientRadius="64">\n'
      '                <item android:offset="0" android:color="#FF2A1F1A" />\n'
      '                <item android:offset="0.65" android:color="#FF1C1715" />\n'
      '                <item android:offset="1" android:color="#FF1A1614" />\n'
      '            </gradient>\n        </aapt:attr>\n    </path>\n</vector>\n']
open(f"{RES}/drawable/ic_launcher_background.xml", "w").write("".join(bg))

# Proof: the icon under a circle mask and a squircle-ish mask, plus the themed version.
S = 8
def render(mono_mode=False):
    im = Image.new("RGBA", (108 * S, 108 * S))
    d = ImageDraw.Draw(im)
    for i in range(54 * S, 0, -2):
        t = i / (64 * S); t = min(1, t)
        col = tuple(int(a + (b - a) * min(1, t / 0.65)) for a, b in zip((0x2A, 0x1F, 0x1A), (0x1C, 0x17, 0x15)))
        if mono_mode: col = (0x30, 0x3A, 0x30)
        d.ellipse([54 * S - i, 50 * S - i, 54 * S + i, 50 * S + i], fill=col)
    for r, c, x, y, on in cells():
        if mono_mode and not on: continue
        color = ("#CFE8CF" if mono_mode else heat(r, c)) if on else EMPTY
        d.rounded_rectangle([x * S, y * S, (x + CELL) * S, (y + CELL) * S], RAD * S, fill=color)
    return im
def masked(im, shape):
    m = Image.new("L", im.size, 0); md = ImageDraw.Draw(m)
    inset = 18 * S  # launcher shows the middle 72dp
    box = [inset, inset, 108 * S - inset, 108 * S - inset]
    if shape == "circle": md.ellipse(box, fill=255)
    else: md.rounded_rectangle(box, 22 * S, fill=255)
    out = Image.new("RGBA", im.size, (240, 240, 240, 255)); out.paste(im, (0, 0), m)
    return out.crop(box).resize((288, 288), Image.LANCZOS)
sheet = Image.new("RGB", (288 * 3 + 40, 288), (240, 240, 240))
for i, im in enumerate([masked(render(), "circle"), masked(render(), "squircle"), masked(render(True), "circle")]):
    sheet.paste(im, (i * 308, 0))
sheet.save(OUT)
